import pg from 'pg';

export const createPool = connectionString => new pg.Pool({ connectionString, max: 10, connectionTimeoutMillis: 5000 });

export async function transaction(pool, work) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await work(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
